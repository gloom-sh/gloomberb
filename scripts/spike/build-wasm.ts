import { createHash } from "crypto";
import { join, resolve } from "path";

/**
 *   bun scripts/spike/build-wasm.ts [--simd]
 *
 * Builds kernels/chart-raster for wasm32-unknown-unknown and writes the
 * module into src/components/chart/composite/raster-kernel.generated.ts as
 * base64, so the browser, the desktop window, Bun and the terminal app all
 * load the same bytes from their own bundle with no asset to ship beside it.
 */
const root = resolve(join(import.meta.dir, "..", ".."));
const crate = join(root, "kernels", "chart-raster");
const simd = process.argv.includes("--simd");
const build = Bun.spawnSync(["cargo", "build", "--release", "--target", "wasm32-unknown-unknown"], {
  cwd: crate,
  env: { ...process.env, ...(simd ? { RUSTFLAGS: "-C target-feature=+simd128" } : {}) },
  stdout: "inherit",
  stderr: "inherit",
});
if (build.exitCode !== 0) throw new Error("cargo build failed");
const bytes = new Uint8Array(await Bun.file(join(crate, "target", "wasm32-unknown-unknown", "release", "chart_raster.wasm")).arrayBuffer());
const sha256 = createHash("sha256").update(bytes).digest("hex");
const out = join(root, "src", "components", "chart", "composite", "raster-kernel.generated.ts");
await Bun.write(out, `// Generated by scripts/spike/build-wasm.ts from kernels/chart-raster. Do not edit.
export const RASTER_KERNEL_SHA256 = "${sha256}";
export const RASTER_KERNEL_BYTES = ${bytes.length};
export const RASTER_KERNEL_SIMD = ${simd};
export const RASTER_KERNEL_BASE64 = "${Buffer.from(bytes).toString("base64")}";
`);
console.log(`${out}: ${bytes.length} bytes, sha256 ${sha256}${simd ? ", simd128" : ""}`);
